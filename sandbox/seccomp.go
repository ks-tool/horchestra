// The workload's syscall filter: a pure-Go classic-BPF program installed with
// prctl(PR_SET_SECCOMP) — no libseccomp/cgo. It is a DENYLIST: syscalls are allowed by default
// and a small set of kernel-attack-surface expanders is refused with EPERM (the action Docker's
// default profile uses, so a workload degrades gracefully instead of dying on SIGSYS).
//
// It is what keeps the read-only root read-only. Everything else here runs the workload with an
// emptied capability bounding set and a non-root id, but nothing in that stops it from calling
// unshare(CLONE_NEWUSER) and holding a full namespaced capability set in a namespace of its own —
// and with CAP_SYS_ADMIN there, mounting a writable tmpfs over any path in the tree. Denying the
// namespace and mount syscalls is what closes that door.
//
// seccompProgram builds the filter and installSeccomp is the only thing that touches the kernel,
// so the whole denylist is decided in code the tests drive directly — an arch table that silently
// stopped filtering is precisely the failure they exist to catch.

type sockFilter struct {
	code uint16
	jt   uint8
	jf   uint8
	k    uint32
}

const (
	// classic-BPF opcodes
	bpfLdWAbs = 0x20 // BPF_LD  | BPF_W   | BPF_ABS
	bpfJeqK   = 0x15 // BPF_JMP | BPF_JEQ | BPF_K
	bpfJgeK   = 0x35 // BPF_JMP | BPF_JGE | BPF_K
	bpfJsetK  = 0x45 // BPF_JMP | BPF_JSET| BPF_K
	bpfRetK   = 0x06 // BPF_RET | BPF_K

	// struct seccomp_data field offsets
	offNr    = 0
	offArch  = 4
	offArgs0 = 16 // args[0]; little-endian, so the low 32 bits sit here

	seccompRetAllow = 0x7fff0000
	seccompRetErrno = 0x00050000 // | errno

	// Linux errno values, spelled out rather than taken from the host's syscall package: the
	// program is compiled for the workload's kernel, not for the machine building it.
	errnoEPERM  = 1
	errnoENOSYS = 38

	// x32SyscallBit marks the x32 ABI on x86_64; the ceiling check denies it along with every
	// other out-of-table number, and the constant remains because the tests name it.
	// seccomp_data.arch still reads AUDIT_ARCH_X86_64
	// for an x32 process, so without this every bare syscall-number comparison below simply
	// misses and the call is allowed.
	x32SyscallBit = 0x40000000

	// cloneNewNamespaces are the CLONE_NEW* flags. clone(2) cannot be denied outright — the Go
	// runtime and every threading libc create threads with it — so it is allowed unless it asks
	// for a new namespace, which is the nested-user-namespace primitive unshare is denied for.
	cloneNewNamespaces = 0x00020000 | // CLONE_NEWNS   (NOT 0x100 — that is CLONE_VM, which every
		//                                thread creation sets; masking on it would deny them all)
		0x02000000 | // CLONE_NEWCGROUP
		0x04000000 | // CLONE_NEWUTS
		0x08000000 | // CLONE_NEWIPC
		0x10000000 | // CLONE_NEWUSER
		0x20000000 | // CLONE_NEWPID
		0x40000000 // CLONE_NEWNET
)

// archFilter is one architecture's filter inputs: the AUDIT_ARCH value seccomp reports, the
// syscall numbers for that ABI and the name table a custom policy is resolved against. Numbers
// are per-architecture, which is why a table exists at all.
type archFilter struct {
	auditArch uint32
	clone     uint32
	clone3    uint32
	denied    []uint32
	// names is this ABI's syscall name table (syscalls.go, generated by hack/gensyscalls from
	// x/sys/unix). It exists so a custom policy can name a syscall rather than number it —
	// numbers differ per ABI, and a policy that silently denied the wrong call on one
	// architecture is the failure this avoids.
	names map[string]uint32
	// maxNr is the highest syscall number the table knows. Everything above it is denied: a
	// denylist is open at the top by nature, and a syscall the kernel grew after this table was
	// generated is exactly the one nobody has decided about yet.
	maxNr uint32
}

