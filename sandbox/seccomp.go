// seccompProgram assembles the BPF filter for goarch. It returns an error for an architecture
// with no table: an unfiltered workload must be a refusal to start, never a silent downgrade.
//
// The layout, and why each branch exists:
//
//	ld arch;  arch != native            -> DENY   (a foreign ABI has different numbers, so the
//	                                               comparisons below would be meaningless)
//	ld nr;    nr > maxNr                -> DENY   (a syscall this build never heard of — one the
//	                                               kernel grew later, or an x32 call, which keeps
//	                                               AUDIT_ARCH_X86_64 and ORs 0x40000000 into the
//	                                               number, landing far above any real one)
//	          nr == clone              -> flags check
//	          nr == clone3             -> ENOSYS  (its flags live behind a pointer seccomp cannot
//	                                               read; ENOSYS makes libc fall back to clone,
//	                                               which IS filtered)
//	          nr in denied             -> DENY
//	                                     -> ALLOW
func seccompProgram(goarch string, policy *SeccompPolicy) ([]sockFilter, error) {
	a, ok := archFilters[goarch]
	if !ok {
		return nil, fmt.Errorf("seccomp: no syscall filter for GOARCH %q", goarch)
	}
	denied, err := applyPolicy(policy, a)
	if err != nil {
		return nil, err
	}
	a.denied = denied

	var f []sockFilter
	stmt := func(code uint16, k uint32) { f = append(f, sockFilter{code: code, k: k}) }
	jmp := func(code uint16, k uint32) int { f = append(f, sockFilter{code: code, k: k}); return len(f) - 1 }

	stmt(bpfLdWAbs, offArch)
	archIdx := jmp(bpfJeqK, a.auditArch) // == native falls through; != jumps to deny
	stmt(bpfLdWAbs, offNr)
	// The ceiling closes the denylist at the top, which is the one thing a denylist cannot do by
	// itself: everything above the highest number this build knows is refused, so a syscall added
	// by a later kernel is denied until the table is regenerated and someone decides about it.
	// It subsumes the x32 check — 0x40000000 is far above any real syscall number.
	ceilIdx := jmp(bpfJgeK, a.maxNr+1)
	cloneIdx := jmp(bpfJeqK, a.clone)
	clone3Idx := jmp(bpfJeqK, a.clone3)
	deniedIdx := make([]int, 0, len(a.denied))
	for _, nr := range a.denied {
		deniedIdx = append(deniedIdx, jmp(bpfJeqK, nr))
	}

	stmt(bpfRetK, seccompRetAllow) // the fallthrough for everything not named above
	denyIdx := len(f)
	stmt(bpfRetK, seccompRetErrno|errnoEPERM)
	enosysIdx := len(f)
	stmt(bpfRetK, seccompRetErrno|errnoENOSYS)

	// clone: allow unless it requests a new namespace.
	cloneCheckIdx := len(f)
	stmt(bpfLdWAbs, offArgs0)
	cloneFlagIdx := jmp(bpfJsetK, cloneNewNamespaces)
	stmt(bpfRetK, seccompRetAllow)
	cloneDenyIdx := len(f)
	stmt(bpfRetK, seccompRetErrno|errnoEPERM)

	// Classic BPF jumps are forward-only 8-bit offsets, which is why every target sits after
	// every jump that reaches it.
	f[archIdx].jf = jumpTo(archIdx, denyIdx)
	f[ceilIdx].jt = jumpTo(ceilIdx, denyIdx)
	f[cloneIdx].jt = jumpTo(cloneIdx, cloneCheckIdx)
	f[clone3Idx].jt = jumpTo(clone3Idx, enosysIdx)
	for _, i := range deniedIdx {
		f[i].jt = jumpTo(i, denyIdx)
	}
	f[cloneFlagIdx].jt = jumpTo(cloneFlagIdx, cloneDenyIdx)
	return f, nil
}

// maxDenied is how many syscalls the denylist can hold. Classic-BPF jumps carry an 8-bit
// displacement, and the longest one here — the arch mismatch at instruction 1 jumping to the
// deny return past every syscall comparison — is 5 + len(denied). A policy that overran it
// would truncate a jump into the middle of the program, so it is refused instead.
const maxDenied = 250

// applyPolicy returns the architecture's denylist with the policy's Deny added and its Allow
// removed. A nil policy returns the built-in list unchanged.
//
// A function rather than a method because SeccompPolicy is the CONTRACT's type (api/sandbox), and
// Go will not let this package hang behaviour off a type it does not own — which is the rule
// working as intended: what a policy MEANS belongs to whoever installs the filter.
func applyPolicy(p *SeccompPolicy, a archFilter) ([]uint32, error) {
	if p == nil || (len(p.Deny) == 0 && len(p.Allow) == 0) {
		return a.denied, nil
	}

	denied := make(map[uint32]struct{}, len(a.denied)+len(p.Deny))
	for _, nr := range a.denied {
		denied[nr] = struct{}{}
	}
	for _, name := range p.Deny {
		nr, err := a.syscallNumber(name)
		if err != nil {
			return nil, err
		}
		denied[nr] = struct{}{}
	}
	// Allow runs last, so a syscall named in both is allowed — the explicit escape hatch wins
	// over the default it was written to override.
	for _, name := range p.Allow {
		nr, err := a.syscallNumber(name)
		if err != nil {
			return nil, err
		}
		delete(denied, nr)
	}

	if len(denied) > maxDenied {
		return nil, fmt.Errorf("seccomp: %d denied syscalls exceeds the %d a classic-BPF jump can reach",
			len(denied), maxDenied)
	}
	return slices.Sorted(maps.Keys(denied)), nil
}

// syscallNumber resolves a policy entry — a syscall name ("io_uring_setup") or a decimal number
// — to this architecture's syscall number. clone and clone3 are refused: they are structural
// branches of the filter, not denylist entries, and naming one would add a comparison the
// branch above it already shadows.
func (a archFilter) syscallNumber(entry string) (uint32, error) {
	name := strings.TrimSpace(entry)
	if name == "" {
		return 0, fmt.Errorf("seccomp: empty syscall name in policy")
	}
	if name == "clone" || name == "clone3" {
		return 0, fmt.Errorf("seccomp: %s is filtered by its flags, not by name; it cannot appear in a policy", name)
	}
	if nr, err := strconv.ParseUint(name, 10, 32); err == nil {
		return uint32(nr), nil
	}
	if nr, ok := a.names[name]; ok {
		return nr, nil
	}
	return 0, fmt.Errorf("seccomp: unknown syscall %q (not in this architecture's table)", name)
}

// jumpTo is the classic-BPF displacement from the instruction at from to the one at to. It panics
// on a backward or out-of-range jump: both are programming errors in the layout above, and a
// silently truncated offset would produce a filter that allows what it claims to deny.
func jumpTo(from, to int) uint8 {
	d := to - from - 1
	if d < 0 || d > 255 {
		panic(fmt.Sprintf("seccomp: jump from %d to %d is out of range", from, to))
	}
	return uint8(d)
}

type sockFprog struct {
	length uint16
	_      [6]byte // pad so filter is 8-byte aligned, matching C struct sock_fprog on 64-bit
	filter *sockFilter
}

// installSeccomp applies the filter to the calling thread and every descendant. It requires
// PR_SET_NO_NEW_PRIVS to have been set first (dropPrivileges does that before calling this), and
// the caller must already be pinned to its OS thread — the filter lands on this thread, and the
// execve that hands control to the workload has to happen on the same one.
//
// It FAILS CLOSED on an architecture with no filter table: dropPrivileges propagates the error
// and the sandbox refuses to exec the workload. Returning nil there would leave a workload
// running with no syscall filter at all while every layer above reported success — a build for
// an unlisted GOARCH is a reason to add a table, not to run unprotected.
func installSeccomp(policy *SeccompPolicy) error {
	prog, err := seccompProgram(runtime.GOARCH, policy)
	if err != nil {
		return err
	}
	fprog := sockFprog{length: uint16(len(prog)), filter: &prog[0]}
	_, _, errno := unix.Syscall(unix.SYS_PRCTL, unix.PR_SET_SECCOMP, unix.SECCOMP_MODE_FILTER,
		uintptr(unsafe.Pointer(&fprog)))
	runtime.KeepAlive(prog)
	if errno != 0 {
		return fmt.Errorf("prctl(SET_SECCOMP): %w", errno)
	}
	return nil
}
